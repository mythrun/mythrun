import { oklch, formatHex, toGamut, wcagContrast } from 'culori'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

export const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900]
const PAPER = { 50:'#F8F4EA',100:'#EFE9DC',200:'#E1D9C6',300:'#C9BFA8',400:'#A89F8A',500:'#877F72',600:'#66604F',700:'#3D3528',800:'#2D2519',900:'#231B12' }
const EMBER = { 50:'#F5E4D3',100:'#ECCDAB',200:'#DCAE7E',300:'#C99562',400:'#B47B4E',500:'#9E6A44',600:'#8A5A3C',700:'#714730',800:'#573624',900:'#3C2619' }
export const SEMANTIC_ANCHORS = {
  success:{hex:'#6D7A3E',anchorStep:500}, warning:{hex:'#B07835',anchorStep:500},
  danger:{hex:'#B55A48',anchorStep:500}, info:{hex:'#4A6B82',anchorStep:600},
}
const toRgb = toGamut('rgb', 'oklch')
const emberOk = Object.fromEntries(STEPS.map((s) => [s, oklch(EMBER[s])]))

function generateRamp(hex, anchorStep) {
  const a = oklch(hex)
  const lShift = a.l - emberOk[anchorStep].l
  const out = {}
  for (const s of STEPS) {
    if (s === anchorStep) { out[s] = hex; continue }
    const l = Math.min(1, Math.max(0, emberOk[s].l + lShift))
    const c = a.c * (emberOk[s].c / emberOk[anchorStep].c)
    // toGamut holds L+H and reduces chroma into sRGB. Out-of-gamut light
    // steps (e.g. warning-50, a near-white cream) clip at the gamut corner,
    // so their MEASURED hue may drift — expected, and judged via tokens.html.
    out[s] = formatHex(toRgb({ mode: 'oklch', l, c, h: a.h }))
  }
  return out
}
export function generatePalette() {
  const palette = { paper: { ...PAPER }, ember: { ...EMBER } }
  for (const [name, { hex, anchorStep }] of Object.entries(SEMANTIC_ANCHORS)) {
    palette[name] = generateRamp(hex, anchorStep)
  }
  for (const name of Object.keys(SEMANTIC_ANCHORS)) {
    const ls = STEPS.map((s) => oklch(palette[name][s]).l)
    for (let i = 1; i < ls.length; i++) {
      if (!(ls[i] < ls[i - 1])) throw new Error(`${name}: non-monotonic L at step ${STEPS[i]}`)
    }
  }
  return palette
}
const RAMPS = ['paper', 'ember', 'success', 'warning', 'danger', 'info']
function toThemeCss(p) {
  const lines = RAMPS.flatMap((r) => STEPS.map((s) => `  --color-${r}-${s}: ${p[r][s]};`))
  return `/* GENERATED by scripts/generate-palette.mjs — do not edit by hand. */\n@theme {\n${lines.join('\n')}\n}\n`
}
function toManifest(p) {
  const colors = {}
  for (const r of RAMPS) for (const s of STEPS) colors[`--color-${r}-${s}`] = p[r][s]
  return { colors }
}
function toAuditHtml(p) {
  const ramp = (r) => `<h2>${r}</h2><div class="ramp">` + STEPS.map((s) => {
    const hex = p[r][s]
    const onL = wcagContrast(hex, p.paper[100]).toFixed(2)
    const onD = wcagContrast(hex, p.paper[900]).toFixed(2)
    return `<div class="sw" style="background:${hex}"><b>${s}</b><span>${hex}</span><span class="cc">L ${onL} · D ${onD}</span></div>`
  }).join('') + `</div>`
  return `<!doctype html><html><head><meta charset="utf-8"><title>Mythrun tokens</title><style>
body{font-family:ui-monospace,monospace;background:${p.paper[100]};color:${p.paper[900]};padding:32px}
.ramp{display:grid;grid-template-columns:repeat(10,1fr);gap:0;margin-bottom:8px;border-radius:6px;overflow:hidden}
.sw{aspect-ratio:1;padding:8px;font-size:9px;display:flex;flex-direction:column;justify-content:space-between;color:#0007}
.sw b{font-size:11px}.cc{opacity:.7}h2{font-size:13px;text-transform:uppercase;letter-spacing:.5px;margin:24px 0 6px}
</style></head><body><h1>Mythrun design tokens — light (contrast: L=on paper-100, D=on paper-900)</h1>${RAMPS.map(ramp).join('')}</body></html>`
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const here = dirname(fileURLToPath(import.meta.url))
  // process.argv[2] = output dir for colors.generated.css + tokens.manifest.json.
  // A passed arg resolves against process.cwd() (normal CLI path semantics — so
  // `build:tokens` run from frontend/ui with `./src/styles` lands there, and the
  // round-trip test's absolute tmpDir is honored verbatim). With NO arg we fall
  // back to a path anchored at this file's dir that reproduces the pre-relocation
  // behavior: write into @mythrun/ui's styles dir. tokens.html is written next to
  // src/ at the package root (../../ from .../src/styles → frontend/ui/tokens.html),
  // matching the pre-relocation location.
  const argDir = process.argv[2]
  const outDir = argDir === undefined
    ? resolve(here, '../../../ui/src/styles')
    : resolve(process.cwd(), argDir)
  const p = generatePalette()
  writeFileSync(resolve(outDir, 'colors.generated.css'), toThemeCss(p))
  writeFileSync(resolve(outDir, 'tokens.manifest.json'), JSON.stringify(toManifest(p), null, 2) + '\n')
  writeFileSync(resolve(outDir, '../../tokens.html'), toAuditHtml(p))
  console.log('generated colors.generated.css, tokens.manifest.json, tokens.html')
}
